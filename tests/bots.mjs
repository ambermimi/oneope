import {strict as assert} from 'node:assert';
import {botCount,botReplies,encouragement} from '../docs/bots.js';
const t=s=>Date.parse(s+'+09:00');
assert.equal(botCount(t('2026-11-02T20:59:59'),0),0);
assert.equal(botCount(t('2026-11-02T21:00:00'),0),1);
assert.equal(botCount(t('2026-11-03T04:59:59'),4),1);
assert.equal(botCount(t('2026-11-03T05:00:00'),50),0);
assert.equal(botCount(t('2026-11-02T23:00:00'),5),2);
assert.equal(botCount(t('2026-11-02T23:00:00'),100),2);
const time=t('2026-11-03T00:01:00');
const msgs=[{sender:'a',body:'授乳中',created:time-180000},{sender:'b',body:'疲れたよ',created:time-179000},{sender:'c',body:'眠れない',created:time-90000}];
const two=botReplies(msgs,time,5);
assert.equal(two.length,2);assert.deepEqual(two.map(x=>x.name),['ともり','こはる']);
assert.deepEqual(botReplies([...msgs].reverse(),time,5),two);
assert.equal(new Set(botReplies(msgs,time,1).map(x=>x.name)).size,1);
assert.equal(botReplies([{sender:'a',body:'hi',created:time-1000}],time,1).length,0);
assert.equal(botReplies(msgs,t('2026-11-03T05:00:00'),1).length,0);
assert.equal(botReplies([{...msgs[0],created:t('2026-11-02T20:59:00')}],time,1).length,0);
assert.match(encouragement('授乳中'),/🍼|🌷/);
assert.match(encouragement('死にたい'),/連絡/);
console.log('Night boundaries, scaling, pacing, stable ordering, delay and encouragement checks passed.');
